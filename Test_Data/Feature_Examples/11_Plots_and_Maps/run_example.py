from jasc_api import Session, series, launch_recording


def run(session):
    curves = session.load("input/curves.csv", name="Curves")
    categories = session.load("input/categories.csv", name="Categories")
    spatial = session.load("input/map.csv", name="Map")
    scattered = session.load("input/scattered_map.csv", name="Scattered map")
    spectral = session.load("input/spectral_map.csv", name="Spectral map", data_kind="table")
    line = session.plot([series(x=(curves, "x"), y=(curves, "sine"))], name="Line")
    scatter = session.plot([series(x=(curves, "x"), y=(curves, "cosine"), plot_type="scatter", marker="o")], name="Scatter")
    markers = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="line_marker", marker=".")], name="Line markers")
    errors = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="errorbar", y_err_column="sigma")], name="Error bars")
    area = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="area")], name="Area")
    dual = session.plot([series(x=(curves, "x"), y=(curves, "sine")), series(x=(curves, "x"), y=(curves, "right_scale"), y_axis="right", color="#e67e22")], name="Dual Y axes")
    bar = session.plot([series(x=(categories, "label"), y=(categories, "value"), plot_type="bar")], name="Bars")
    horizontal = session.plot([series(x=(categories, "label"), y=(categories, "value"), plot_type="barh")], name="Horizontal bars")
    histogram = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="histogram", histogram_bins=12)], name="Histogram")
    box = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="box", distribution_columns=["sine", "cosine"])], name="Box")
    violin = session.plot([series(x=(curves, "x"), y=(curves, "sine"), plot_type="violin", distribution_columns=["sine", "cosine"])], name="Violin")
    pie = session.plot([series(x=(categories, "label"), y=(categories, "value"), plot_type="pie")], name="Pie")
    donut = session.plot([series(x=(categories, "label"), y=(categories, "value"), plot_type="donut")], name="Donut")
    voronoi = session.plot([series(x=(categories, "label"), y=(categories, "value"), plot_type="voronoi")], name="Voronoi")
    map_series = series(x=(spatial, "x"), y=(spatial, "y"), z=(spatial, "z"), plot_type="heatmap", surface_render_mode="native", color_map="viridis", show_global_maximum=True)
    heatmap = session.plot([map_series], name="Native heatmap")
    contour = session.plot([series(x=(spatial, "x"), y=(spatial, "y"), z=(spatial, "z"), plot_type="contour")], name="Contours")
    filled = session.plot([series(x=(spatial, "x"), y=(spatial, "y"), z=(spatial, "z"), plot_type="contourf")], name="Filled contours")
    irregular = session.plot([series(x=(scattered, "x"), y=(scattered, "y"), z=(scattered, "z"), plot_type="heatmap", surface_render_mode="interpolated", grid_resolution=40, show_data_points=True)], name="Scattered interpolation")
    spectral_heat = session.plot([series(x=(spectral, "X"), y=(spectral, "Y"), z=(spectral, "Intensity"), plot_type="spectra_heatmap", spectral_column="shift", spectral_center=240.)], name="Spectral heatmap")
    spectral_contour = session.plot([series(x=(spectral, "X"), y=(spectral, "Y"), z=(spectral, "Intensity"), plot_type="spectra_contour", spectral_column="shift", spectral_center=240.)], name="Spectral contours")
    spectral_fill = session.plot([series(x=(spectral, "X"), y=(spectral, "Y"), z=(spectral, "Intensity"), plot_type="spectra_contourf", spectral_column="shift", spectral_center=240.)], name="Spectral filled contours")
    comparison = session.compare([line, scatter, bar, histogram, box, donut, heatmap, contour, spectral_heat], name="Family comparison", rows=3, columns=3, panel_labels=True)
    synced = session.compare([heatmap, filled], name="Synchronized maps", rows=1, columns=2, match_x=True, match_y=True)
    grid = session.map_analysis(map_series, operation="grid", name="Rendered grid")
    cut = session.map_analysis(map_series, operation="horizontal", name="Horizontal cut", parameters=[0.])
    diagonal = session.map_analysis(map_series, operation="line", name="Diagonal cut", parameters=[-2., -2., 2., 2., 41])
    roi = session.map_analysis(map_series, operation="roi", name="ROI", parameters=[-1., 1., -1., 1.])
    contours = session.map_analysis(map_series, operation="contours", name="Contour vertices")
    for sheet in [grid, cut, diagonal, roi, contours]:
        session.export_data(sheet, "tables/" + sheet.name + ".csv")
    # Export every subtype so this is a renderer example as well as saved states.
    session.export_plot(line, "figures/line.png")
    session.export_plot(scatter, "figures/scatter.png")
    session.export_plot(markers, "figures/markers.png")
    session.export_plot(errors, "figures/errors.png")
    session.export_plot(area, "figures/area.png")
    session.export_plot(dual, "figures/dual.png")
    session.export_plot(bar, "figures/bar.png")
    session.export_plot(horizontal, "figures/barh.png")
    session.export_plot(histogram, "figures/histogram.png")
    session.export_plot(box, "figures/box.png")
    session.export_plot(violin, "figures/violin.png")
    session.export_plot(pie, "figures/pie.png")
    session.export_plot(donut, "figures/donut.png")
    session.export_plot(voronoi, "figures/voronoi.png")
    session.export_plot(heatmap, "figures/heatmap.png")
    session.export_plot(contour, "figures/contour.png")
    session.export_plot(filled, "figures/contourf.png")
    session.export_plot(irregular, "figures/scattered.png")
    session.export_plot(spectral_heat, "figures/spectra_heatmap.png")
    session.export_plot(spectral_contour, "figures/spectra_contour.png")
    session.export_plot(spectral_fill, "figures/spectra_contourf.png")
    session.export_plot(comparison, "figures/comparison.png")
    session.export_plot(synced, "figures/synchronized.png")


if __name__ == "__main__":
    launch_recording(__file__)
